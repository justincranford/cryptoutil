package main

import (
	"fmt"
	"strings"
)

func render(m model, r registry, inv inventory) []byte {
	var out strings.Builder

	pools, pods, dbs, claims := 0, 0, 0, 0
	for _, rel := range inv.Releases {
		dbs += len(rel.Databases)

		pools += len(rel.Workloads)
		for _, w := range rel.Workloads {
			pods += w.Bounds.Min
			if w.Pool == poolDisk {
				claims += w.Bounds.Min
			}
		}
	}

	fmt.Fprint(&out, "# Kubernetes deployment tree (generated planning inventory)\n\n")
	fmt.Fprint(&out, "> PROPOSED, not deployed. Do not edit this file. Regenerate with the command in [Kubernetes deployment contract](../../../docs/kubernetes-deployment-contract.md#regeneration-and-review).\n\n")
	fmt.Fprintf(&out, "Inputs: [registry](../registry.yaml), [model](k8s-model.json); grammar version %d; run `%s`; revision `%s`.\n\n", m.Version, m.Run, m.Revision)
	fmt.Fprintf(&out, "Registry: %d standalone + %d products + %d suite = %d tier scopes. No unregistered fourth product is synthesized.\n\n",
		len(r.Members), len(r.Products), len(r.Suites), len(r.Members)+len(r.Products)+len(r.Suites))
	fmt.Fprintf(&out, "Selected inventory: %d releases + 1 shared infrastructure namespace = %d namespaces; %d backend pools; sum(pool.min) = %d app pods; %d logical databases on EACH PostgreSQL node; %d active SQLite claims.\n\n",
		len(inv.Releases), len(inv.Releases)+1, pools, pods, dbs, claims)
	fmt.Fprint(&out, "Default full-matrix derivation: (7 standalone members + (1 + 5 + 1) product members + 7 suite members) = 21 member occurrences per mode. Pools per member across pg/mixed-mem/mixed-disk/mem/disk = 1+2+2+1+1. At min=max=2: `21*7*2 = 294` app pods; `21*3 = 63` PostgreSQL databases; `21*2*2 = 84` SQLite claims. These baseline formulas do not override selected inputs.\n\n")
	fmt.Fprint(&out, "A pool is a replica group, NOT another product. In mixed modes a PS-ID has two pools (four default pods). SQLite pods have independent databases, not HA/shared state. `i01` maps to ordinal `0`, `i02` to `1`; later ordinals are new slots.\n\n")
	fmt.Fprint(&out, "Pod names are StatefulSet controller identities. PVC names follow `data-<statefulset>-<ordinal>`. Listed dormant max-capacity pods/PVCs are reservations, not claims that controllers have created them. All Secrets below are names only, never material.\n\n")
	fmt.Fprint(&out, "Local cluster grammar: Compose project `cu-"+m.Run+"-cluster`, Docker network `cu-"+m.Run+"-nodes`, K3s server `cu-"+m.Run+"-server-0`, workers `cu-"+m.Run+"-agent-{0,1}`. Bootstrap is planned, not generated here. Host ports and node counts will be configurable.\n\n")
	fmt.Fprintf(&out, "## Shared infrastructure: `%s`\n\n", inv.InfraNamespace)
	fmt.Fprint(&out, "Owner: cluster bootstrap/infra Helm release, never an application release. Namespace selectors admit only explicit run+release clients. Database roles deny other releases' databases. Shared LGTM is run-level observability, NOT mutually untrusted tenant isolation.\n\n")
	fmt.Fprintf(&out, "Steady-state dependency pods: collector=%d, LGTM=%d; when PostgreSQL is selected, leader=%d and logical follower=%d (not a failover pair). Only the actual selected dependencies are listed below. Transient Jobs and cluster system pods are excluded.\n\n",
		m.Infrastructure.Collector, m.Infrastructure.LGTM, m.Infrastructure.Leader, m.Infrastructure.Follower)
	renderObjects(&out, inv.Infra)
	fmt.Fprint(&out, "\nController-created dependency pods:\n\n")
	renderObjects(&out, inv.InfraPods)
	fmt.Fprint(&out, "\n## Release index\n\n| Selector | Namespace | Helm release | Pools |\n|---|---|---|---:|\n")

	for _, rel := range inv.Releases {
		fmt.Fprintf(&out, "| `%s` | `%s` | `%s` | %d |\n", rel.Key, rel.Namespace, rel.Helm, len(rel.Workloads))
	}

	for _, rel := range inv.Releases {
		fmt.Fprintf(&out, "\n## `%s`\n\n", rel.Key)
		fmt.Fprintf(&out, "Namespace `%s`; Helm release `%s`; labels `cu.io/run=%s`, `cu.io/release=%s`. Namespace is bootstrap-owned; the app Helm release owns its non-retained resources.\n\n",
			rel.Namespace, rel.Helm, inv.Run, rel.Helm)
		fmt.Fprint(&out, "Namespace resources (unseal and pepper are release-scoped, preserving effective Compose sharing):\n\n")
		renderObjects(&out, rel.Objects)

		if len(rel.Databases) > 0 {
			fmt.Fprintf(&out, "\nDB endpoints: `postgres-leader.%s.svc.%s:5432` (OLTP), `postgres-follower.%s.svc.%s:5432` (OLAP only). Replication never gates application startup/readiness.\n\n", inv.InfraNamespace, m.ClusterDomain, inv.InfraNamespace, m.ClusterDomain)
			fmt.Fprint(&out, "| PS-ID | Database on leader and follower | Runtime role | Publication / subscription |\n|---|---|---|---|\n")

			for _, db := range rel.Databases {
				fmt.Fprintf(&out, "| `%s` | `%s` | `%s` | `%s` / `%s` |\n", db.PSID, db.Name, db.Role, db.Publication, db.Subscription)
			}
		}

		fmt.Fprintf(&out, "\nOTLP: `collector.%s.svc.%s:4317` (mTLS; HTTP option 4318). Only public HTTPS 8080 is Service-routed; admin mTLS remains 127.0.0.1:9090, probed by exec.\n", inv.InfraNamespace, m.ClusterDomain)

		for _, w := range rel.Workloads {
			fmt.Fprintf(&out, "\n### `%s` (%s, min=%d max=%d)\n\n", w.Name, w.Pool, w.Bounds.Min, w.Bounds.Max)
			fmt.Fprintf(&out, "Exact selectors: run=%s, release=%s, psid=%s, pool=%s. Member configs: `%s-framework`, `%s-domain`; pod overlay: `%s-config` + Downward API pod-name file.\n\n", inv.Run, rel.Helm, w.PSID, w.Pool, w.PSID, w.PSID, w.Name)

			if w.Pool == poolPG {
				fmt.Fprintf(&out, "Pooled HTTPS: `%s:8080`; local TLS-SNI `%s`; all replicas share only this release/member's database. HPA bounds are values, including equal min/max.\n\n", w.ServiceFQDN, w.Host)
			} else {
				fmt.Fprint(&out, "No pooled user-traffic Service: each SQLite pod is addressed independently. Headless Service is discovery only. Scaling is explicit, within configured bounds, not CPU-driven autoscaling.\n\n")
			}

			renderObjects(&out, w.Objects)
			fmt.Fprint(&out, "\n| Pod | Instance Service | Leaf Secret | PVC | Legacy slot | State |\n|---|---|---|---|---|---|\n")

			for _, p := range w.Pods {
				state, pvc := "active", p.PVC
				if !p.Active {
					state = "reserved"
				}

				if pvc == "" {
					pvc = "-"
				}

				fmt.Fprintf(&out, "| `%s` | `%s` | `%s` | `%s` | `%s` | %s |\n", p.Name, p.Service, p.TLS, pvc, p.LegacySlot, state)
			}

			fmt.Fprint(&out, "\nExact pod DNS / local TLS-SNI names (no host port per app):\n\n")

			for _, p := range w.Pods {
				fmt.Fprintf(&out, "- `%s` -> `%s`; instance Service `%s.%s.svc.%s:8080`.\n", p.FQDN, p.Host, p.Service, rel.Namespace, m.ClusterDomain)
			}
		}
	}

	fmt.Fprint(&out, "\n## Isolation and validation boundary\n\n")
	fmt.Fprint(&out, "- Shared infrastructure is an intentional exception to namespace/network isolation; allowlists, SQL grants, per-pod client certificates, and telemetry resource attributes preserve provenance.\n")
	fmt.Fprint(&out, "- Release Secrets/RBAC, network rules, resource requests, trust bundles, storage class, image digests, and probe parameters must be validated against rendered Helm objects in implementation. This inventory names their owners; it is NOT a Helm renderer or live-cluster verifier.\n")
	fmt.Fprint(&out, "- Actual Pod/PVC inventory uses active/min versus reserved/max semantics. Controller-created resource UIDs/IPs and Job pod suffixes are runtime-assigned and must be matched by ownerReferences/labels, never predicted.\n")

	return []byte(out.String())
}

func renderObjects(out *strings.Builder, objects []object) {
	for _, o := range objects {
		fmt.Fprintf(out, "- %s `%s`\n", o.Kind, o.Name)
	}
}
